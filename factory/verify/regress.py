"""Turn a COUNTEREXAMPLE into a reproducible pytest regression file."""

from __future__ import annotations

from pathlib import Path
from typing import List, Tuple

from .contracts import Contract
from .solve import ObligationResult, Verdict

_HEADER = '''"""Regression generated by factory.verify from a solver COUNTEREXAMPLE.

contract: {cid}   obligation: {oid} ({text})
This test fails while the implementation violates the contract on the recorded
inputs and passes once it is fixed.  It runs the real code (needs the software-factory
repo importable, e.g. PYTHONPATH=<repo>); do not weaken it, change the contract instead.
"""
from factory.verify.replay import call_symbol

SYMBOL = {symbol!r}
SOURCE_FILE = {source!r}
SEMANTICS = {semantics!r}
INPUTS = {inputs!r}
'''


def _args(contract: Contract) -> str:
    return ", ".join(n for n, _ in contract.params)


def _fn(name: str, contract: Contract, text: str, extra: str = "") -> str:
    sig = _args(contract) + extra
    return (f"def {name}({sig}):\n    try:\n        return bool({text})\n"
            f"    except ZeroDivisionError:\n        return False\n")


def render_regression(contract: Contract, ob: ObligationResult, source_file: str) -> Tuple[str, str]:
    """Return ``(file_name, source_text)`` for one COUNTEREXAMPLE obligation."""
    if ob.verdict is not Verdict.COUNTEREXAMPLE or not ob.counterexample:
        raise ValueError("a regression can only be generated from a replayed COUNTEREXAMPLE")
    parts = [_HEADER.format(cid=contract.contract_id, oid=ob.id, text=ob.text, symbol=contract.symbol,
                            source=str(Path(source_file).resolve()), semantics=contract.semantics,
                            inputs=ob.counterexample["inputs"])]
    parts.append("def old(v):\n    return v  # old(x) is the original argument value (pure function)\n")
    pre = " and ".join(f"({p.text})" for p in contract.preconditions) or "True"
    parts.append(_fn("_pre", contract, pre))
    parts.append("def _declared(exc, " + _args(contract) + "):\n    return (" + " or ".join(
        f"(exc == {e.exception!r} and _when_{i}({_args(contract)}))" for i, e in enumerate(contract.errors)) + ")\n"
        if contract.errors else "def _declared(exc, " + _args(contract) + "):\n    return False\n")
    for i, e in enumerate(contract.errors):
        parts.append(_fn(f"_when_{i}", contract, e.when_text))
    kind = ob.kind
    body = ["def test_counterexample_is_fixed():",
            "    assert _pre(**INPUTS), 'recorded inputs no longer satisfy the precondition; regenerate'",
            "    out = call_symbol(SYMBOL, SOURCE_FILE, INPUTS, SEMANTICS)"]
    if kind in ("post", "inv"):
        clause = next(c for c in contract.postconditions + contract.invariants if c.id == ob.id)
        parts.append(_fn("_holds", contract, clause.text, ", result"))
        body += ["    if out.kind == 'raise':",
                 "        assert _declared(out.exc, **INPUTS), f'undeclared {out.exc} raised on {INPUTS}'",
                 "    else:",
                 "        assert _holds(**INPUTS, result=out.value), f'{INPUTS} -> {out.value} violates the contract'"]
    elif kind == "err":
        e = next(e for e in contract.errors if e.id == ob.id)
        parts.append(_fn("_when", contract, e.when_text))
        body += ["    if _when(**INPUTS):",
                 f"        assert out.kind == 'raise' and out.exc == {e.exception!r}, f'expected {e.exception} on {{INPUTS}}, got {{out}}'"]
    else:
        body += ["    if out.kind == 'raise':",
                 "        assert _declared(out.exc, **INPUTS), f'undeclared {out.exc} raised on {INPUTS}'"]
    parts.append("\n".join(body) + "\n")
    safe = "".join(ch if ch.isalnum() else "_" for ch in f"{contract.contract_id}_{ob.id}").lower()
    return f"test_regress_{safe}.py", "\n\n".join(parts)


def write_regressions(report, out_dir) -> List[Path]:
    """Write one regression file per COUNTEREXAMPLE in a gate report."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for contract, target, result in report.results:
        if result is None or target is None:
            continue
        for ob in result.obligations:
            if ob.verdict is Verdict.COUNTEREXAMPLE:
                name, text = render_regression(contract, ob, target.file)
                p = out / name
                p.write_text(text, encoding="utf-8")
                written.append(p)
    return written
